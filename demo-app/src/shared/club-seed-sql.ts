// The SQL for `supabase/seeds/chapters.sql` and `supabase/seeds/events.sql`, as pure functions of
// the TypeScript that describes the same rows. `roots/app/scripts/seed-club.mjs` writes the files;
// `test/club-seed.test.ts` regenerates them and fails if the committed ones differ.
import { CHAPTERS } from './chapter-types.js';
import { EVENT_TEMPLATES, eventIdOf, seedRsvps, venueOf } from './events-seed.js';
import { memberIdOf } from './chapter-types.js';
import type { MemberRow } from './member-types.js';

const q = (s: string | null) => (s === null ? 'null' : `'${s.replace(/'/g, "''")}'`);

const HEADER = (what: string) =>
  `-- GENERATED by \`pnpm --filter @demo-app/app seed:club\` from demo-app/src/shared/${what} — do not edit.\n` +
  `-- A test regenerates this file and fails when it differs, so edit the TypeScript and re-run.\n`;

export function chaptersSql(): string {
  const rows = CHAPTERS.map(
    (c) => `  (${q(c.name)}, ${q(c.slug)}, ${q(c.tagline)}, ${q(c.meets)}, ${q(c.venue)}, ${q(c.leadId)})`,
  );
  return (
    HEADER('chapter-types.ts') +
    '\n-- CASCADE: events reference chapters, and RSVPs reference events. Re-seeding chapters re-seeds both.\n' +
    'truncate table public.chapters cascade;\n\n' +
    'insert into public.chapters (name, slug, tagline, meets, venue, lead_id) values\n' +
    rows.join(',\n') +
    ';\n'
  );
}

export function eventsSql(members: readonly MemberRow[]): string {
  const events = EVENT_TEMPLATES.map((t, i) => {
    const at = `interval '${t.at[0]} hours ${t.at[1]} minutes'`;
    // The next `weekday` from today (today counts), plus whole weeks — `dayOffsetOf` in SQL.
    const day = `current_date + ((${t.weekday} - extract(dow from current_date)::int + 7) % 7) + ${7 * t.week}`;
    return `  (${q(eventIdOf(i))}, ${q(t.title)}, ${q(t.kind)}, ${q(t.chapter)}, (${day})::timestamptz + ${at}, ${t.minutes}, ${q(venueOf(t))}, ${t.capacity}, ${q(memberIdOf(t.host))}, ${q(t.blurb)})`;
  });
  const rsvps = seedRsvps(members).map(([e, m]) => `  (${q(e)}, ${q(m)})`);
  return (
    HEADER('events-seed.ts') +
    '\n-- Dates are offsets from `current_date`, like the timeslots, so the calendar never drifts into\n' +
    '-- the past between rehearsal and the take.\n' +
    'truncate table public.events cascade;\n\n' +
    'insert into public.events (id, title, kind, chapter, starts_at, minutes, venue, capacity, host_id, blurb) values\n' +
    events.join(',\n') +
    ';\n\n' +
    '-- The guard trigger refuses RSVPs to events that have started, and the seed holds RSVPs to the\n' +
    '-- two past events on purpose (they are who attended). The seed is history, not a request.\n' +
    'alter table public.event_rsvps disable trigger event_rsvps_guard;\n\n' +
    'insert into public.event_rsvps (event_id, member_id) values\n' +
    rsvps.join(',\n') +
    ';\n\n' +
    'alter table public.event_rsvps enable trigger event_rsvps_guard;\n'
  );
}
