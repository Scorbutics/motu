#!/usr/bin/env node
// <id>.req.toml → everything about a region that is a DECISION already written in the spec:
//
//   app/<page>/…-region.ts                 the app-side region type ([state])
//   <id>.archipelago.ts                    root, slots, islands (bind + intents), the source
//   <id>.evidence.ts                       one flow per clause `flow` — motu then checks them too
//   islands/<slot>.evidence.ts             one scenario per world × island, data from the fixtures
//   roots/lagoon/src/regions/<id>.tsx      seed + channel (first world) + the other worlds
//   test/<id>.req.rules.ts                 one typed predicate per clause `rule` (fast-check)
//
// What it does NOT generate: components, the source, fixture data, the page. Those are written to
// satisfy the spec, and checked against it.
//
//   node experiments/req-region/gen-region.mjs host-app/motu/src/archipelagos/share-links/share-links.req.toml
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const SPEC = resolve(process.argv[2])
const APP = resolve(dirname(SPEC), '../../../..')            // host-app/
const MOTU = join(APP, 'motu')
const HEADER = (what) => `// GENERATED by experiments/req-region/gen-region.mjs from ${SPEC.slice(APP.length + 1)} — do not edit.\n// ${what}\n`

// ── a TOML subset ────────────────────────────────────────────────────────────────────────────────
const doc = {}
let cur = null
for (const raw of readFileSync(SPEC, 'utf8').split('\n')) {
  const line = raw.replace(/^\s+|\s+$/g, '')
  if (!line || line.startsWith('#')) continue
  let m
  if ((m = line.match(/^\[\[(\w+)\]\]$/))) { (doc[m[1]] ??= []).push((cur = {})); continue }
  if ((m = line.match(/^\[(\w+)\]$/))) { cur = doc[m[1]] = {}; continue }
  if ((m = line.match(/^(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|true|false)\s*(#.*)?$/))) { cur[m[1]] = m[2] === 'true' ? true : m[2] === 'false' ? false : JSON.parse(m[2]); continue }
  throw new Error(`cannot read: ${raw}`)
}
const region = doc.region
const id = region.id
const pascal = id.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())
const camel = pascal[0].toLowerCase() + pascal.slice(1)
const pageDir = region.page.replace(/^\//, '')
const state = Object.entries(doc.state).map(([key, v]) => {
  const [type, note] = v.split('#').map((s) => s.trim())
  return { key, type, owner: note.split(/\s|—/)[0], note: note.replace(/^\w+\s*(—\s*)?/, '') }
})
const source = doc.source
const produced = source.produces.split(/\s+/)
const islands = doc.island.map((i) => {
  const [event, intent] = i.asks.split('→').map((s) => s.trim())
  const states = i.states ? i.states.split('|').map((st) => {
    const [name, assigns] = st.split(':').map((x) => x.trim())
    return { name, seed: Object.fromEntries(assigns.split(',').map((a) => a.split('=').map((x) => x.trim()))) }
  }) : null
  return { slot: i.slot, element: `x-${i.slot}`, reads: i.reads.split(/\s+/), event, intent, states }
})
const worlds = doc.world ?? []
const clauses = doc.clause

// ── 1. the app-side region type ──────────────────────────────────────────────────────────────────
const typeImports = new Set()
for (const s of state) for (const t of s.type.match(/\b[A-Z]\w+/g) ?? []) typeImports.add(t)
const regionType = `${HEADER(`The ${id} region's state, as the APP names it. The spec decides; this file only states it.`)}import type { HostRegion } from "@motu/types"
${typeImports.size ? `import type { ${[...typeImports].join(', ')} } from "@/src/${pageDir}/${id}-source"\n` : ''}
export interface ${pascal.replace(/s$/, '')}Region {
${state.map((s) => `  /** ${s.owner.toUpperCase()}${s.note ? ` — ${s.note}` : ''} */\n  ${s.key}: ${s.type}`).join('\n')}
}

/** Keys an ISLAND produces. None: every island here ASKS (an intent) and the source answers. */
export type Produced${pascal.replace(/s$/, '')}Keys = never

export type ${pascal.replace(/s$/, '')}HostRegion = HostRegion<${pascal.replace(/s$/, '')}Region, Produced${pascal.replace(/s$/, '')}Keys>
`
const R = `${pascal.replace(/s$/, '')}Region`
mkdirSync(join(APP, 'app', pageDir), { recursive: true })
writeFileSync(join(APP, 'app', pageDir, `${pageDir}-region.ts`), regionType)

// ── 2. the archipelago ───────────────────────────────────────────────────────────────────────────
const slotProp = (slot) => slot.replace(/^[^-]+-/, '')        // share-list → list
const archipelagoFile = `${HEADER('Root, slots, who reads what and who asks for what — all of it from the spec.')}import { archipelago } from '@motu/core';
import type { ElementTypes } from '../../islands/registry';
import type { ${R}, Produced${pascal.replace(/s$/, '')}Keys } from '@/app/${pageDir}/${pageDir}-region';
import { ${source.id}Source } from '@/src/${pageDir}/${id}-source';
import { ${region.root} } from '@/components/${pageDir}/${region.root}';

export const ${camel}Archipelago = archipelago<${R}, Pick<ElementTypes, ${islands.map((i) => `'${i.element}'`).join(' | ')}>, Produced${pascal.replace(/s$/, '')}Keys>()({
  id: '${id}',
  root: ${region.root},
  slots: {
${islands.map((i) => `    ${slotProp(i.slot)}: { slot: '${i.slot}' },`).join('\n')}
  },
  islands: [
${islands.map((i) => `    {
      slot: '${i.slot}',
      element: '${i.element}',
      bind: [${i.reads.map((k) => `'${k}'`).join(', ')}],
      intents: { '${i.event}': '${i.intent}' },
    },`).join('\n')}
  ],
  sources: {
    ${source.id}: ${source.id}Source,
  },
} as const,
{ ownership: true, wiring: true, produced: true });
`
writeFileSync(join(MOTU, 'src/archipelagos', id, `${id}.archipelago.ts`), archipelagoFile)

// ── 3. region flows from clause `flow`s ──────────────────────────────────────────────────────────
const defaultWorld = worlds[0]?.id
const flows = clauses.filter((c) => c.flow).map((c) => {
  const steps = []
  let world = null
  const last = () => (steps.length ? steps[steps.length - 1] : (steps.push({}), steps[0]))
  for (const part of c.flow.split('·').map((s) => s.trim())) {
    let m
    if ((m = part.match(/^in (\S+)$/))) { if (m[1] !== defaultWorld) world = m[1]; continue }
    if ((m = part.match(/^click (.+)$/))) { steps.push({ click: m[1] }); continue }
    if ((m = part.match(/^(shows|hides) ([\w-]+): (.+)$/))) {
      const st = last(); st.expectRender ??= {}
      const prev = st.expectRender[m[2]]
      const want = typeof prev === 'string' ? { text: prev } : prev ?? {}
      // a second assertion on a slot already asserted in this step becomes its own step
      if ((m[1] === 'shows' && want.text) || (m[1] === 'hides' && want.notText)) { steps.push({ expectRender: { [m[2]]: m[1] === 'shows' ? m[3] : { notText: m[3] } } }); continue }
      st.expectRender[m[2]] = m[1] === 'shows' ? (want.notText ? { ...want, text: m[3] } : m[3]) : { ...want, notText: m[3] }
      continue
    }
    if ((m = part.match(/^holds (\w+) = (.+)$/))) { const st = last(); (st.expect ??= {})[m[1]] = JSON.parse(m[2]); continue }
    throw new Error(`${c.id}: cannot read flow step "${part}"`)
  }
  return `  {
    // ${c.id} (${c.provenance}) — ${c.says}
    name: ${JSON.stringify(`${c.id} — ${c.says}`)},${world ? `\n    world: ${JSON.stringify(world)},` : ''}
    steps: ${JSON.stringify(steps)},
  },`
})
writeFileSync(join(MOTU, 'src/archipelagos', id, `${id}.evidence.ts`), `${HEADER('One flow per clause that names what a person does and sees. motu checks these like any flow.')}import type { RegionScenario } from '@motu/runtime/mock';

export const scenarios: RegionScenario[] = [
${flows.join('\n')}
];
`)

// ── 4. island scenarios: every world × the keys each island reads, data from the fixtures ────────
const fixtures = `../shared/${id}-evidence.js`
const keyFixture = (w, key) => (w[key] ? w[key] : `${w.id.toUpperCase().replace(/-/g, '_')}_${key.replace(/([A-Z])/g, '_$1').toUpperCase()}`)
for (const i of islands) {
  const used = new Set()
  // The island's own named states if the spec gives them, else one per world — and the worlds only
  // when they actually differ in what this island reads (identical scenarios fail motu's data-flow).
  const named = i.states ?? worlds.map((w) => ({ name: w.id, seed: Object.fromEntries(i.reads.filter((k) => w[k]).map((k) => [k, w[k]])) }))
  const scenarios = named.map(({ name, seed: over }) => {
    const seed = i.reads.map((k) => {
      const v = over[k] ?? `WORLD.${k}`
      if (/^[A-Z]/.test(v)) used.add(v.split('.')[0])
      return `${k}: ${v}`
    })
    return `  { name: ${JSON.stringify(name)}, seed: { ${seed.join(', ')} } },`
  })
  writeFileSync(join(MOTU, 'src/islands', `${i.slot}.evidence.ts`), `${HEADER(`${i.slot}'s states: one per world the spec names. The data is the app's typed fixtures.`)}import type { Scenario } from '@motu/runtime/mock';
import { ${[...used].join(', ')} } from '${fixtures}';

export const scenarios: Scenario[] = [
${scenarios.join('\n')}
];
`)
  void keyFixture
}

// ── 5. the lagoon: seed (host-fed keys), the source over the first world, the others as worlds ───
const hostKeys = state.filter((s) => s.owner === 'host').map((s) => s.key)
writeFileSync(join(MOTU, 'roots/lagoon/src/regions', `${id}.tsx`), `${HEADER('What the page establishes, and the source over the fixture port of each world the spec names.')}import { overridesFor, defineWorlds } from '@motu/react';
import { channelFrom } from '@motu/core';
import { ${camel}Archipelago } from '../../../../src/archipelagos/${id}/${id}.archipelago.js';
import { WORLD, fixturePort } from '../../../../src/shared/${id}-evidence.js';

export const ${camel}Region = overridesFor(${camel}Archipelago, {
  seed: { ${hostKeys.map((k) => `${k}: WORLD.${k}`).join(', ')} },
  channels: [
    channelFrom({ to: ${camel}Archipelago, id: '${source.id}', channelName: '${id}: the page’s ${source.id} source', args: [fixturePort(${worlds[0].links}), { now: () => new Date(WORLD.now) }] }),
  ],
});

/**
 * Every other world the spec names: the same source, its port answering a different table.
 * A LITERAL \`defineWorlds({…})\`, because motu's static checks read worlds from the first such call
 * in the lagoon's sources and do not follow a spread.
 */
export const ${camel}Worlds = defineWorlds({
${worlds.slice(1).map((w) => `  ${JSON.stringify(w.id)}: {
    description: ${JSON.stringify(`${id}: the port answers ${w.links}`)},
    regions: { '${id}': { channels: { ${source.id}: [fixturePort(${w.links}), { now: () => new Date(WORLD.now) }] } } },
  },`).join('\n')}
});
`.replace(`import { WORLD, fixturePort } from`, `import { WORLD, fixturePort, ${[...new Set(worlds.map((w) => w.links))].join(', ')} } from`))

// ── 6. source rules → typed predicates for the fast-check runner ─────────────────────────────────
const rules = clauses.filter((c) => c.rule).map((c) => {
  const m = c.rule.match(/^at (creation|settled)(?: when (.+?))? => (.+)$/)
  if (!m) throw new Error(`${c.id}: rule "${c.rule}" is not "at <point> [when <expr>] => <expr>"`)
  const names = 's, now, created, token, dismissed, failed, message, before, revoked, listed, port, same'
  return `  { id: ${JSON.stringify(c.id)}, says: ${JSON.stringify(c.says)}, at: "${m[1]}",
    when: ({ ${names} }: Ctx) => Boolean(${m[2] ?? 'true'}),
    then: ({ ${names} }: Ctx) => Boolean(${m[3]}) },`
})
mkdirSync(join(APP, 'test'), { recursive: true })
writeFileSync(join(APP, 'test', `${id}.req.rules.ts`), `${HEADER('The clauses with a `rule`, as typed predicates over the source. test/' + id + '.req.test.ts runs them.')}/* eslint-disable @typescript-eslint/no-unused-vars */
import type { Ctx, Rule } from './${id}.req.meaning.ts'

export const RULES: Rule[] = [
${rules.join('\n')}
]
`)

console.log(`${id}: region type · archipelago · ${flows.length} flow(s) · ${islands.length} island evidence file(s) × ${worlds.length} world(s) · lagoon module · ${rules.length} rule(s)`)
